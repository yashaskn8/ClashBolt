"""Fail-closed CI audit for executed tests and *actual* branch coverage.

Read JUnit and coverage.py JSON generated by the real PostgreSQL test job.
This is a regression floor, not a claim of complete project coverage.
"""

import json
import math
import sys
from pathlib import Path
from xml.etree import ElementTree

MIN_TEST_CASES = 278
MIN_COMBINED_COVERAGE = 82.0
MIN_BRANCH_ONLY_COVERAGE = 80.0
EXPECTED_SKIPS = {
    ("test_target_host", "test_native_execution_and_verification_in_deployed_target"),
    ("test_target_host", "test_live_instances_have_distinct_uids_and_kernel_resource_limits"),
}
MODULE_MINIMUMS = {
    "backend/clashbolt/accounts.py": 70.0,
    "backend/clashbolt/backup.py": 80.0,
    "backend/clashbolt/fixture_runner.py": 85.0,
    "backend/clashbolt/store.py": 85.0,
    "backend/clashbolt/target_db.py": 90.0,
    "backend/clashbolt/target_service.py": 95.0,
    "backend/clashbolt/verification_jobs.py": 92.0,
    "backend/clashbolt/witness.py": 70.0,
}


def validate(junit_xml: Path, coverage_json: Path) -> dict:
    root = ElementTree.parse(junit_xml).getroot()
    if root.tag not in ("testsuite", "testsuites"):
        raise ValueError("JUnit has an unexpected root element")
    if root.tag == "testsuites" and any(child.tag != "testsuite" for child in root):
        raise ValueError("JUnit contains unexpected top-level elements")
    suites = list(root.iter("testsuite"))
    cases = list(root.iter("testcase"))
    direct_cases = {id(case) for suite in suites for case in suite if case.tag == "testcase"}
    if len(direct_cases) != len(cases):
        raise ValueError("JUnit contains test cases outside a direct test suite")
    if not suites or len(cases) < MIN_TEST_CASES:
        raise ValueError(
            f"Test report has {len(cases)} cases; at least {MIN_TEST_CASES} required"
        )
    for suite in suites:
        descendants = list(suite.iter("testcase"))
        for field, actual in (
            ("tests", len(descendants)),
            ("skipped", sum(case.find("skipped") is not None for case in descendants)),
            ("failures", sum(case.find("failure") is not None for case in descendants)),
            ("errors", sum(case.find("error") is not None for case in descendants)),
        ):
            reported = suite.get(field)
            if reported is None or not reported.isdecimal() or int(reported) != actual:
                raise ValueError(
                    f"JUnit suite {suite.get('name', '<unnamed>')} has inconsistent {field}"
                )
    identities = [(case.get("classname"), case.get("name")) for case in cases]
    if any(not classname or not name for classname, name in identities):
        raise ValueError("JUnit contains test cases without stable identities")
    if len(set(identities)) != len(identities):
        raise ValueError("JUnit contains duplicate test cases")
    if any(
        int(suite.get(field, "0")) != 0
        for suite in suites for field in ("failures", "errors")
    ):
        raise ValueError("JUnit reports a failed or errored test")
    if any(case.find("failure") is not None or case.find("error") is not None
           for case in cases):
        raise ValueError("JUnit contains failed or errored test cases")

    skips = []
    for case in cases:
        if case.find("skipped") is not None:
            module = (case.get("classname") or "").split(".")[-1]
            skips.append((module, case.get("name") or ""))
    if len(skips) != len(EXPECTED_SKIPS) or set(skips) != EXPECTED_SKIPS:
        raise ValueError(f"Unexpected or missing test skips: {sorted(skips)}")

    report = json.loads(coverage_json.read_text(encoding="utf-8"))
    if report.get("meta", {}).get("branch_coverage") is not True:
        raise ValueError("Statement-only coverage is not acceptable")
    totals = report["totals"]
    branches = totals["num_branches"]
    if type(branches) is not int or branches <= 0:
        raise ValueError("No branch decisions were measured")
    covered = totals["covered_branches"]
    if not isinstance(covered, int) or isinstance(covered, bool) or not 0 <= covered <= branches:
        raise ValueError("Invalid covered branch count")
    branch_pct = 100 * covered / branches
    combined_pct = totals["percent_covered"]
    if (
        type(combined_pct) not in (int, float)
        or not math.isfinite(combined_pct)
        or not 0 <= combined_pct <= 100
    ):
        raise ValueError("Invalid combined coverage percentage")
    if combined_pct < MIN_COMBINED_COVERAGE:
        raise ValueError(f"Combined coverage {combined_pct:.2f}% below floor")
    if branch_pct < MIN_BRANCH_ONLY_COVERAGE:
        raise ValueError(f"Branch-only coverage {branch_pct:.2f}% below floor")

    files = report["files"]
    if len(files) < 25:
        raise ValueError("Coverage input has unexpectedly few source modules")
    for module, minimum in MODULE_MINIMUMS.items():
        if module not in files:
            raise ValueError(f"Missing critical module in coverage: {module}")
        percentage = files[module]["summary"]["percent_covered"]
        if (
            type(percentage) not in (int, float)
            or not math.isfinite(percentage)
            or not 0 <= percentage <= 100
        ):
            raise ValueError(f"Invalid critical module coverage: {module}")
        if percentage < minimum:
            raise ValueError(
                f"Critical module {module} coverage {percentage:.2f}% < {minimum:.2f}%"
            )
    return {
        "tests_executed": len(cases) - len(skips),
        "expected_host_skips": len(skips),
        "combined_coverage": round(combined_pct, 2),
        "branch_only_coverage": round(branch_pct, 2),
        "branch_decisions_measured": branches,
        "critical_modules_checked": len(MODULE_MINIMUMS),
    }


def main() -> int:
    if len(sys.argv) != 3:
        raise SystemExit(
            "Usage: python ci/check-quality-report.py <junit.xml> <coverage.json>"
        )
    summary = validate(Path(sys.argv[1]), Path(sys.argv[2]))
    print(json.dumps(summary, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
